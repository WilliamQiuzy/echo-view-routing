#!/usr/bin/env python
"""Group the round-3 neighbour-swap check (scripts/round3_neighbor_check.py) by error type (diagnostic only).

Reads neighbor_check.json and splits the fragments into A4C called A5C with an A5C neighbour, A4C called A5C without
one, and all other errors. For each group, surroundings and stage it counts the fragments whose mean probability picks
the reference class, and the source recordings where most of their fragments do (each recording counted once).
Writes neighbor_check_groups.md next to the input unless --out is given.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

CLASSES = ["PLAX", "PSAX", "A4C", "A5C", "SC4C"]
A4C, A5C = CLASSES.index("A4C"), CLASSES.index("A5C")
VARIANTS = ("original", "isolated", "same_class_neighbours", "other_clip_neighbours")
STAGES = ("local", "context", "output")


def groups(rows: list[dict]) -> dict[str, list[dict]]:
    swap = [r for r in rows if r["label"] == A4C and r["variants"]["original"]["output"]["argmax"] == A5C]
    return {"all errors": rows,
            "A4C called A5C, an A5C neighbour": [r for r in swap if A5C in r["neighbour_labels"]],
            "A4C called A5C, no A5C neighbour": [r for r in swap if A5C not in r["neighbour_labels"]],
            "other errors": [r for r in rows if r not in swap]}


def cell(group: list[dict], variant: str, stage: str) -> str:
    have = [r for r in group if variant in r["variants"]]
    right = [r["variants"][variant][stage]["argmax"] == r["label"] for r in have]
    by_rec: dict[str, list[bool]] = defaultdict(list)
    for r, ok in zip(have, right):
        by_rec[r["video_id"]].append(ok)
    majority = sum(sum(v) > len(v) / 2 for v in by_rec.values())
    return f"{sum(right)}/{len(have)} ({majority}/{len(by_rec)})"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("json"); ap.add_argument("--out", default=None)
    a = ap.parse_args(); src = Path(a.json)
    rows = json.loads(src.read_text())["rows"]
    md = ["# Neighbour-swap check by error type (round 3, step 3; diagnostic only)", "",
          "Generated by scripts/summarize_neighbor_check.py from neighbor_check.json. A cell gives the fragments whose mean",
          "probability at that stage picks the reference class, then in brackets the source recordings where most of their",
          "fragments do (each recording counted once).", ""]
    for name, grp in groups(rows).items():
        md += [f"## {name}: {len(grp)} fragments, {len({r['video_id'] for r in grp})} recordings", "",
               "| Surroundings | local (convolutions) | context (attention) | output |", "|---|---|---|---|"]
        md += [f"| {v.replace('_', ' ')} | " + " | ".join(cell(grp, v, s) for s in STAGES) + " |" for v in VARIANTS]
        md.append("")
    out = Path(a.out) if a.out else src.with_name("neighbor_check_groups.md")
    out.write_text("\n".join(md)); print("\n".join(md))


if __name__ == "__main__":
    main()
