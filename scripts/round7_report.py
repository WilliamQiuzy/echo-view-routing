#!/usr/bin/env python
"""Round-7 report over the three seed runs of scripts/round7_local_readout.py (configs/experiments/local_readout_v1.yaml):
start conditions, span classification with errors in each direction and separation, paired per-seed bootstrap
contrasts (P2 - P1 first), the full systems against ASRF's default, E1's B3 tuned and the strongest previous
configuration, the final goal, flips with their clips and sessions, and the pre-declared terms and reading.
Writes report.json and report.md into --out.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.model_development_protocol import session_of  # noqa: E402
from scripts.report_model_development import BOOT_SEED, N_BOOT, paired_bootstrap  # noqa: E402
from scripts.report_model_development_round2 import category, metrics, read  # noqa: E402

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.stats import rankdata  # noqa: E402

HALVES, SEEDS, ARMS = ("selection", "calibration"), (0, 1, 2), ("P0", "P1", "P2")
A4C, A5C = 2, 3
SPAN = ("accuracy", "A4C recall", "A5C recall", "separation (AUC)")
SYS = ("multi segment F1@50", "multi boundary recall", "native macro-F1", "native cuts per clip")
PAIRS = (("P2", "P1"), ("P1", "P0"), ("P2", "P0"))
FLOORS, RECALL_MIN, MARGIN = {"selection": 0.973, "calibration": 0.980}, 0.95, 0.01


def auc(score: np.ndarray, pos: np.ndarray) -> float:
    if pos.all() or not pos.any():
        return float("nan")
    r = rankdata(score); n1 = int(pos.sum())
    return float((r[pos].sum() - n1 * (n1 + 1) / 2) / (n1 * (len(pos) - n1)))


def span_measures(d: pd.DataFrame, arm: str) -> dict:
    m = d[f"margin_{arm}"].to_numpy(); lab = d["label"].to_numpy(); pred = np.where(m >= 0, A5C, A4C)
    return {"accuracy": float((pred == lab).mean()), "A4C recall": float((pred[lab == A4C] == A4C).mean()),
            "A5C recall": float((pred[lab == A5C] == A5C).mean()), "separation (AUC)": auc(m, lab == A5C)}


def span_bootstrap(d: pd.DataFrame, new: str, ref: str) -> dict:
    """new - ref on the same spans, resampling sessions of the spans' source clips."""
    sess = d["source"].map(session_of).to_numpy(); units = np.unique(sess); rows = {s: np.flatnonzero(sess == s) for s in units}
    rng = np.random.default_rng(BOOT_SEED); a, b = span_measures(d, new), span_measures(d, ref); draws = {k: [] for k in SPAN}
    for _ in range(N_BOOT):
        dd = d.iloc[np.concatenate([rows[s] for s in rng.choice(units, size=units.size, replace=True)])]
        x, y = span_measures(dd, new), span_measures(dd, ref)
        for k in SPAN:
            draws[k].append(x[k] - y[k])
    return {k: {"delta": a[k] - b[k], "ci95": [float(np.nanpercentile(draws[k], 2.5)), float(np.nanpercentile(draws[k], 97.5))]} for k in SPAN}


def summarise(per_seed: dict, names: tuple) -> dict:
    return {"per_seed": per_seed, "category": {m: category([per_seed[k][m]["ci95"] for k in per_seed], len(SEEDS)) for m in names}}


def goal(tables: dict, strongest: dict) -> dict:
    out = {}
    for h in HALVES:
        ms = [metrics(tables[k][h]) for k in SEEDS]; mean = float(np.mean([m["segment_f1_50_multi"] for m in ms]))
        rec, nat = min(m["boundary_recall_multi"] for m in ms), min(m["native_macro_f1"] for m in ms)
        out[h] = {"mean_segment_f1_50": mean, "strongest": strongest[h], "min_recall": rec, "min_native_f1": nat,
                  "passes": bool(mean >= strongest[h] + MARGIN and rec >= RECALL_MIN and nat >= FLOORS[h])}
    return {**out, "passes_both": out["selection"]["passes"] and out["calibration"]["passes"]}


def terms(ca: dict, cb: dict) -> dict:
    cls = [ca[f"P2 - P1|{h}"]["category"][m] for h in HALVES for m in ("accuracy", "separation (AUC)")]
    seg = [cb[f"P2 - P1|{h}"]["category"]["multi segment F1@50"] for h in HALVES]
    return {"classification_gain": "consistent (higher)" in cls and "consistent (lower)" not in cls,
            "system_gain": "consistent (higher)" in seg and "consistent (lower)" not in seg}


def reading(t: dict) -> str:
    if not t["classification_gain"]:
        return "no classification gain of P2 over P1: the hypothesis ends; read this way, the patch tokens add no detectable A4C/A5C information"
    if not t["system_gain"]:
        return "a classification gain of P2 over P1 without a system gain: recorded as a local gain only"
    return "classification and system gains of P2 over P1: worth further testing; the final goal is judged separately"


def ci(v: dict, scale: float = 1.0) -> str:
    return f"{scale * v['delta']:+.2f} [{scale * v['ci95'][0]:+.2f}, {scale * v['ci95'][1]:+.2f}]"


def markdown(r: dict) -> list[str]:
    md = ["# Round 7: global against local readouts of the frozen E1 encoder (generated by scripts/round7_report.py)", "",
          "## Start conditions", ""]
    for k, s in enumerate(r["seeds"]):
        md.append(f"- seed {k}: P0 reproduces V0 {s.get('p0_reproduces_v0')}; token 0 vs global {s['parity']['token0_vs_global']:.1e}; "
                  f"parity reference {s['parity']['parity_reference']:.1e}, cache {s['parity']['parity_cache']:.1e}; capacity {s['capacity']}; "
                  f"{s['minutes']:.0f} min")
    md += ["", "## Span classification (validation spans with an A4C or A5C majority; s0 / s1 / s2)", "",
           "| half | rule | accuracy | A4C recall | A5C recall | separation (AUC) | A4C read as A5C (clips) | A5C read as A4C (clips) |", "|---|---|---|---|---|---|---|---|"]
    for h in HALVES:
        for arm in ("vote", *ARMS):
            cs = [s["classification"][h][arm] for s in r["seeds"]]; ds = [s["directional"][h][arm] for s in r["seeds"]]
            sep = " / ".join(f"{x[h][arm]['separation (AUC)']:.3f}" for x in r["span_points"]) if arm in ARMS else "-"
            md.append(f"| {h} | {arm} | " + " / ".join(f"{c['accuracy']:.3f}" for c in cs) + " | " + " / ".join(f"{c['recall_A4C']:.3f}" for c in cs)
                      + " | " + " / ".join(f"{c['recall_A5C']:.3f}" for c in cs) + f" | {sep} | "
                      + " / ".join(f"{d['A4C read as A5C']['spans']} ({d['A4C read as A5C']['clips']})" for d in ds) + " | "
                      + " / ".join(f"{d['A5C read as A4C']['spans']} ({d['A5C read as A4C']['clips']})" for d in ds) + " |")
    md += ["", "Paired span contrasts (points per seed for rates, AUC x100; 95% session-bootstrap intervals):", ""]
    for key, c in r["contrasts_span"].items():
        for m in SPAN:
            md.append(f"- {key.replace('|', ', ')}, {m}: " + "; ".join(f"s{k} {ci(c['per_seed'][k][m], 100)}" for k in SEEDS) + f" -> {c['category'][m]}")
    md += ["", "## Systems (all clips; segment F1@50 per seed, mean)", "", "| system | selection | calibration |", "|---|---|---|"]
    for s_name in ("default", "mean", *ARMS):
        cells = []
        for h in HALVES:
            v = [s["metrics"][f"{s_name}|all|{h}"]["segment_f1_50_multi"] for s in r["seeds"]]
            cells.append(" / ".join(f"{x:.4f}" for x in v) + f" ({np.mean(v):.4f})")
        md.append(f"| {s_name} | {cells[0]} | {cells[1]} |")
    md += ["", "Paired system contrasts (points; 95% bootstrap intervals):", ""]
    for key, c in r["contrasts_system"].items():
        for m in SYS:
            md.append(f"- {key.replace('|', ', ')}, {m}: " + "; ".join(f"s{k} {ci(c['per_seed'][k][m], 100)}" for k in SEEDS) + f" -> {c['category'][m]}")
    md += ["", "## Final goal (unchanged)", "", "| arm | half | mean F1@50 (strongest + 0.01) | min recall | min native F1 (floor) | passes |", "|---|---|---|---|---|---|"]
    for arm, g in r["goals"].items():
        for h in HALVES:
            o = g[h]
            md.append(f"| {arm} | {h} | {o['mean_segment_f1_50']:.4f} ({o['strongest'] + MARGIN:.4f}) | {o['min_recall']:.3f} | {o['min_native_f1']:.3f} ({FLOORS[h]}) | {'yes' if o['passes'] else 'no'} |")
    md += ["", "## Flips (stream units; clips, sessions in brackets)", "", "| comparison | half | A5C fixed s0 / s1 / s2 | A4C broken s0 / s1 / s2 |", "|---|---|---|---|"]
    for comp in ("P2 vs P1", "P1 vs P0", "P2 vs P0", "P0 vs default", "P1 vs default", "P2 vs default"):
        for h in HALVES:
            f = [s["flips"][f"{comp}|{h}"] for s in r["seeds"]]
            cell = lambda key: " / ".join(f"{x[key]['n']} ({x[key]['clips']}, {x[key]['sessions']})" for x in f)  # noqa: E731
            md.append(f"| {comp} | {h} | {cell('units: A5C fixed')} | {cell('units: A4C broken')} |")
    md += ["", "## Terms and reading", "", "```", json.dumps(r["terms"], indent=1), "```", "", f"Reading: **{r['reading']}**"]
    return md


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", required=True, help="seed0_dir,seed1_dir,seed2_dir"); ap.add_argument("--spec", default="runs/md_round4/spec.json")
    ap.add_argument("--out", required=True); ap.add_argument("--allow-sanity", action="store_true", help="plumbing check on sanity runs only")
    a = ap.parse_args(); out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    runs = [Path(x) for x in a.runs.split(",")]; seeds = [json.loads((rd / "seed.json").read_text()) for rd in runs]
    if [s["seed"] for s in seeds] != list(SEEDS) or (any(s["sanity"] for s in seeds) and not a.allow_sanity):
        raise SystemExit("expected the three full seed runs 0, 1, 2")
    spec = json.loads(Path(a.spec).read_text())
    spans = {k: {h: pd.read_csv(rd / f"spans_{h}.csv", dtype={"source": str, "seq_id": str}) for h in HALVES} for k, rd in enumerate(runs)}
    spans = {k: {h: d[d["label"].isin([A4C, A5C])].reset_index(drop=True) for h, d in v.items()} for k, v in spans.items()}
    span_points = [{h: {arm: span_measures(spans[k][h], arm) for arm in ARMS} for h in HALVES} for k in SEEDS]
    ca = {f"{n} - {r}|{h}": summarise({k: span_bootstrap(spans[k][h], n, r) for k in SEEDS}, SPAN) for n, r in PAIRS for h in HALVES}
    tab = {arm: {k: {h: read(runs[k], f"rows_{arm}_all_{h}") for h in HALVES} for k in SEEDS} for arm in ("default", *ARMS)}
    b3 = {h: read(Path(spec["encoders"]["E1"]["simple_run"]), f"rows_b3_tuned_main_{h}") for h in HALVES}
    strongest_t = {"selection": read(Path(spec["encoders"]["E0"]["simple_run"]), "rows_b3_tuned_main_selection"),
                   "calibration": read(Path(spec["b7_run"]), "rows_B7_b3_calibration")}
    strongest = {h: metrics(t)["segment_f1_50_multi"] for h, t in strongest_t.items()}
    cb = {}
    for n, rf in PAIRS:
        for h in HALVES:
            cb[f"{n} - {rf}|{h}"] = summarise({k: paired_bootstrap(tab[n][k][h], tab[rf][k][h]) for k in SEEDS}, SYS)
    for arm in ARMS:
        for h in HALVES:
            cb[f"{arm} - ASRF default|{h}"] = summarise({k: paired_bootstrap(tab[arm][k][h], tab["default"][k][h]) for k in SEEDS}, SYS)
            cb[f"{arm} - B3 tuned (E1)|{h}"] = summarise({k: paired_bootstrap(tab[arm][k][h], b3[h]) for k in SEEDS}, SYS)
            cb[f"{arm} - strongest previous|{h}"] = summarise({k: paired_bootstrap(tab[arm][k][h], strongest_t[h]) for k in SEEDS}, SYS)
    goals = {arm: goal(tab[arm], strongest) for arm in ARMS}
    t = terms(ca, cb)
    report = {"runs": [str(x) for x in runs], "strongest": strongest, "span_points": span_points, "contrasts_span": ca,
              "contrasts_system": cb, "goals": goals, "terms": t, "reading": reading(t), "seeds": seeds}
    (out / "report.json").write_text(json.dumps(report, indent=1, default=str))
    md = markdown(report); (out / "report.md").write_text("\n".join(md) + "\n"); print("\n".join(md))


if __name__ == "__main__":
    main()
